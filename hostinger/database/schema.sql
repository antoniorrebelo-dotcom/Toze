-- Tabela das rifas do Cocoloto (MySQL / MariaDB).
-- Só é preciso numa base de dados NOVA (a da Hostinger já tem esta tabela).

CREATE TABLE IF NOT EXISTS rifas (
  id       INT          NOT NULL PRIMARY KEY,
  position VARCHAR(8)   NOT NULL DEFAULT '0',
  seller   VARCHAR(100) NOT NULL DEFAULT '',
  buyer    VARCHAR(100) NOT NULL DEFAULT '',
  ranking  TINYINT      NOT NULL DEFAULT 0,
  KEY idx_position (position)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Cria os números 1 a 2000 (a grelha usa até 25 linhas x 80 colunas)
INSERT IGNORE INTO rifas (id)
SELECT a.n + b.n * 10 + c.n * 100 + d.n * 1000 + 1 AS id
FROM (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
      UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) a,
     (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
      UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) b,
     (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
      UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) c,
     (SELECT 0 n UNION ALL SELECT 1) d
HAVING id <= 2000;
